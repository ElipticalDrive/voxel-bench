"""Checks the encyclopedia's entries (docs/schemes/<category>/<slug>.md) and rewrites the
index in docs/schemes/README.md.

  scripts/schemes.py          # check, then write the index
  scripts/schemes.py --check  # check only; exit 1 if the index is out of date

Needs Python 3.11+ (tomllib).
"""
import pathlib
import re
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent / "docs" / "schemes"
CATEGORIES = ["storage", "traversal", "visibility", "discovery", "geometry", "draw", "prepass", "shading", "meshes", "post", "world"]
STATUSES = ["idea", "built", "measured", "rejected"]
ORIGINS = ["user", "project", "literature"]
FIELDS = {"title": str, "category": str, "status": str, "components": list, "related": list, "origin": str, "sources": list}
SECTIONS = ["What it is", "How it works", "In this project", "Measured"]
OPTIONAL = ["Open questions"]
BEGIN, END = "<!-- index: generated by scripts/schemes.py -->", "<!-- end index -->"


def load():
    entries, problems = {}, []
    for path in sorted(ROOT.glob("*/*.md")):
        where = path.relative_to(ROOT)
        text = path.read_text(encoding="utf-8")
        m = re.match(r"\+\+\+\n(.*?)\n\+\+\+\n", text, re.S)
        if not m:
            problems.append(f"{where}: no +++ header")
            continue
        try:
            head = tomllib.loads(m.group(1))
        except tomllib.TOMLDecodeError as e:
            problems.append(f"{where}: {e}")
            continue
        for field, kind in FIELDS.items():
            if not isinstance(head.get(field), kind):
                problems.append(f"{where}: `{field}` missing or not a {kind.__name__}")
        for field in head.keys() - FIELDS.keys():
            problems.append(f"{where}: unknown field `{field}`")
        if head.get("category") != path.parent.name:
            problems.append(f"{where}: category {head.get('category')!r} is not its folder")
        if path.parent.name not in CATEGORIES:
            problems.append(f"{where}: unknown category folder (one of {', '.join(CATEGORIES)})")
        if head.get("status") not in STATUSES:
            problems.append(f"{where}: status {head.get('status')!r} (one of {', '.join(STATUSES)})")
        if head.get("origin") not in ORIGINS:
            problems.append(f"{where}: origin {head.get('origin')!r} (one of {', '.join(ORIGINS)})")
        sections = re.findall(r"^## (.+)$", text[m.end():], re.M)
        want = SECTIONS + [s for s in OPTIONAL if s in sections]
        if sections != want:
            problems.append(f"{where}: sections {sections}, expected {want}")
        if path.stem in entries:
            problems.append(f"{where}: slug also used by {entries[path.stem][0]}")
        entries[path.stem] = (where, head)
    for slug, (where, head) in entries.items():
        for r in head.get("related", []):
            if r not in entries:
                problems.append(f"{where}: related entry {r!r} does not exist")
            elif r == slug:
                problems.append(f"{where}: related to itself")
    return entries, problems


def index(entries):
    lines = []
    for cat in CATEGORIES:
        rows = sorted(((h["title"], where, h) for where, h in entries.values() if h["category"] == cat), key=lambda r: r[0].lower())
        if not rows:
            continue
        lines += [f"### {cat.capitalize()}", ""]
        for title, where, h in rows:
            comps = ", ".join(f"`{c.split('/', 1)[1]}`" for c in h["components"])
            note = f" ({comps})" if comps else ""
            lines.append(f"- [{title}]({where.as_posix()}){note}: {h['status']}, {h['origin']}")
        lines.append("")
    return "\n".join(lines).rstrip("\n")


def main():
    entries, problems = load()
    for p in problems:
        print(p)
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    a, b = text.index(BEGIN) + len(BEGIN), text.index(END)
    new = text[:a] + "\n" + index(entries) + "\n" + text[b:]
    if "--check" in sys.argv[1:]:
        if new != text:
            print("docs/schemes/README.md: index out of date (run scripts/schemes.py)")
            problems.append("index")
    elif new != text:
        readme.write_text(new, encoding="utf-8")
    print(f"{len(entries)} entries, {len(problems)} problems")
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
